    private void btnAnadirIntegranteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAnadirIntegranteActionPerformed
        String nombreIntegrante = javax.swing.JOptionPane.showInputDialog(
            this,
            "Nombre del integrante del equipo:",
            "Añadir integrante",
            javax.swing.JOptionPane.PLAIN_MESSAGE
        );

        if (nombreIntegrante != null && !nombreIntegrante.trim().isEmpty()) {
            String limpio = nombreIntegrante.trim();
            proyectoActual.agregarIntegrante(limpio);
            modeloIntegrantes.addElement(limpio);
        }
    }//GEN-LAST:event_btnAnadirIntegranteActionPerformed

    private void btnEliminarIntegranteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarIntegranteActionPerformed
        int indiceSeleccionado = listaIntegrantesVisual.getSelectedIndex();

        if (indiceSeleccionado == -1) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Selecciona un integrante de la lista para eliminarlo.",
                "Sin selección",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        proyectoActual.eliminarIntegrante(indiceSeleccionado);
        modeloIntegrantes.remove(indiceSeleccionado);
    }//GEN-LAST:event_btnEliminarIntegranteActionPerformed

    /**
     * @param args the command line arguments
     */
    private void cargarIntegrantes() {
        modeloIntegrantes.clear();
        for (String integrante : proyectoActual.getIntegrantes()) {
            modeloIntegrantes.addElement(integrante);
        }
    }


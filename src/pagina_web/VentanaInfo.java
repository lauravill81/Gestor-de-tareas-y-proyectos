class PanelDisenoAvanzado extends javax.swing.JPanel {
        public PanelDisenoAvanzado() {
            this.setOpaque(false);
        }

        @Override
        protected void paintComponent(java.awt.Graphics g) {
            java.awt.Graphics2D g2d = (java.awt.Graphics2D) g.create();
            // Suavizado para que los puntos se vean redondos y no cuadrados
            g2d.setRenderingHint(java.awt.RenderingHints.KEY_ANTIALIASING, java.awt.RenderingHints.VALUE_ANTIALIAS_ON);
        
            int w = getWidth();
            int h = getHeight();

            // COLORES SOLICITADOS: Degradado de Blanco a Azul muy claro (Grisáceo)
            java.awt.Color colorSuperior = java.awt.Color.WHITE;
            java.awt.Color colorInferior = new java.awt.Color(230, 235, 245); // El tono de tu dashboard
        
            java.awt.GradientPaint gp = new java.awt.GradientPaint(0, 0, colorSuperior, 0, h, colorInferior);
            g2d.setPaint(gp);
            g2d.fillRect(0, 0, w, h);

            // DIBUJO DE LA MALLA (Puntos de ingeniería)
            g2d.setColor(new java.awt.Color(200, 220, 255, 250)); // Gris azulado con transparencia
            int espacio = 25; // Espaciado entre puntos
            for (int x = 0; x < w; x += espacio) {
                for (int y = 0; y < h; y += espacio) {
                    g2d.fillOval(x, y, 2, 2);
                }
            }
            g2d.dispose();
        }
    }



    private void btnAgregarTareaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarTareaActionPerformed
        String nombreTarea = javax.swing.JOptionPane.showInputDialog(
            this,
            "Nombre de la tarea:",
            "Añadir tarea",
            javax.swing.JOptionPane.PLAIN_MESSAGE
        );

        if (nombreTarea != null && !nombreTarea.trim().isEmpty()) {
            String limpio = nombreTarea.trim();
            proyectoActual.agregarTareaConDetalle(limpio);
            modeloLista.addElement(limpio);
            listaTareasVisual.setSelectedIndex(modeloLista.size() - 1);
        }
    }//GEN-LAST:event_btnAgregarTareaActionPerformed

    private void btnEliminarTareaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarTareaActionPerformed
        int indiceSeleccionado = listaTareasVisual.getSelectedIndex();

        if (indiceSeleccionado == -1) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Selecciona una tarea de la lista para eliminarla.",
                "Sin selección",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        proyectoActual.eliminarTareaConDetalle(indiceSeleccionado);
        modeloLista.remove(indiceSeleccionado);

        if (!modeloLista.isEmpty()) {
            int nuevoIndice = Math.min(indiceSeleccionado, modeloLista.size() - 1);
            listaTareasVisual.setSelectedIndex(nuevoIndice);
        }
    }//GEN-LAST:event_btnEliminarTareaActionPerformed

    private void cmbResponsableActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbResponsableActionPerformed
        if (actualizandoCombos) return;
        int idx = listaTareasVisual.getSelectedIndex();
        if (idx >= 0 && idx < proyectoActual.getDetalleTareas().size()) {
            Object sel = cmbResponsable.getSelectedItem();
            proyectoActual.getDetalleTareas().get(idx)
                    .setResponsable(sel != null ? sel.toString() : "Sin asignar");
        }
    }//GEN-LAST:event_cmbResponsableActionPerformed

    private void cmbEstadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbEstadoActionPerformed
        if (actualizandoCombos) return;
        int idx = listaTareasVisual.getSelectedIndex();
        if (idx >= 0 && idx < proyectoActual.getDetalleTareas().size()) {
            Object sel = cmbEstado.getSelectedItem();
            proyectoActual.getDetalleTareas().get(idx)
                    .setEstado(sel != null ? sel.toString() : "por iniciar");
        }
    }//GEN-LAST:event_cmbEstadoActionPerformed

